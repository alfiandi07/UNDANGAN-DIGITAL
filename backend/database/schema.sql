-- Membuat database dan tabel KasirKu
CREATE DATABASE IF NOT EXISTS ASMUdanganDigital
CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE ASMUdanganDigital;
DROP TABLE IF EXISTS detail_transaksi; -- 1. Hapus tabel anak paling bawah
DROP TABLE IF EXISTS transaksi;        -- 2. Hapus tabel anak transaksi
DROP TABLE IF EXISTS produk;           -- 3. Baru hapus produk
DROP TABLE IF EXISTS pengguna;         -- 4. Baru hapus pengguna
CREATE TABLE produk (
id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
nama VARCHAR(100) NOT NULL UNIQUE,
harga INT UNSIGNED NOT NULL,
stok INT UNSIGNED NOT NULL DEFAULT 0,
kategory VARCHAR(100) NOT NULL,
created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);
CREATE TABLE pengguna (
id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
nama VARCHAR(100) NOT NULL,
email VARCHAR(150) NOT NULL UNIQUE,
password VARCHAR(255) NOT NULL, -- hash bcrypt, bukan password asli
peran ENUM('admin', 'creator') NOT NULL DEFAULT 'creator',
created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);
CREATE TABLE transaksi (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  id_pengguna INT UNSIGNED NOT NULL,
  total_harga INT UNSIGNED NOT NULL,
  status ENUM('pending', 'sukses', 'batal') NOT NULL DEFAULT 'pending',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (id_pengguna) REFERENCES pengguna(id) ON DELETE CASCADE
);

CREATE TABLE detail_transaksi (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  id_transaksi INT UNSIGNED NOT NULL,
  id_produk INT UNSIGNED NOT NULL,
  jumlah INT UNSIGNED NOT NULL,
  harga_satuan INT UNSIGNED NOT NULL,
  FOREIGN KEY (id_transaksi) REFERENCES transaksi(id) ON DELETE CASCADE,
  FOREIGN KEY (id_produk) REFERENCES produk(id) ON DELETE CASCADE
);